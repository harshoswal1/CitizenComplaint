import { DatabaseSync } from 'node:sqlite';
import { getDb } from '../db/db.ts';
import type { Complaint, EmailStatus } from '../models/types.ts';
import { handleEmailDeliveryConfirmed, handleEmailDeliveryFailed } from './rankingService.ts';

export interface SendEmailOptions {
  complaintId: string;
  isRetry?: boolean;
  simulateDelivery?: boolean; // For testing or local sandbox
  deliveryOutcome?: 'DELIVERED' | 'FAILED';
  customDb?: DatabaseSync;
}

export interface EmailDispatchResult {
  deliveryId: string;
  complaintId: string;
  attemptNumber: number;
  recipientEmail: string;
  isTestRecipient: boolean;
  subject: string;
  status: EmailStatus;
  providerReference: string;
}

export function dispatchComplaintEmail(options: SendEmailOptions): EmailDispatchResult {
  const db = options.customDb || getDb();
  const now = new Date().toISOString();

  const complaint = db.prepare(`SELECT * FROM complaints WHERE id = ?`).get(options.complaintId) as Complaint | undefined;
  if (!complaint) {
    throw new Error(`Complaint ${options.complaintId} not found`);
  }

  // Determine recipient
  const isTestMode = process.env.NODE_ENV !== 'production';
  const testRecipient = process.env.TEST_EMAIL_RECIPIENT || 'test-civic-officer@kolhapur.gov.local';
  
  // Look up mapped official email for department
  const mapping = db.prepare(`
    SELECT default_official_email, department_name FROM category_mappings
    WHERE authority_id = ? AND category = ?
  `).get(complaint.authority_id, complaint.category) as any;

  const officialRecipient = mapping?.default_official_email || 'prokmc29@gmail.com';
  const recipientEmail = isTestMode ? testRecipient : officialRecipient;

  // Calculate attempt number
  const prevAttempts = db.prepare(`
    SELECT COUNT(*) as count FROM email_deliveries WHERE complaint_id = ?
  `).get(options.complaintId) as any;
  const attemptNumber = (prevAttempts?.count || 0) + 1;

  const subject = `New Civic Complaint — ${complaint.category.replace(/_/g, ' ')} — ${complaint.locality} — ${complaint.id}`;
  const mapLink = `https://www.google.com/maps?q=${complaint.latitude},${complaint.longitude}`;

  const environmentNotice = isTestMode
    ? `\n[TESTING ENVIRONMENT NOTICE]: This email was dispatched to test recipient '${testRecipient}'. It is a sandbox test submission and has NOT been delivered to the real government authority yet.\n`
    : '';

  const body = `CITIZEN CIVIC COMPLAINT SUBMISSION
==========================================
${environmentNotice}
Complaint Reference ID : ${complaint.id}
Category               : ${complaint.category.replace(/_/g, ' ')}
Subtype                : ${complaint.subtype || 'General'}
Locality / Area        : ${complaint.locality}
Administrative Region  : ${complaint.administrative_area}
Geographic Coordinates : ${complaint.latitude.toFixed(6)}, ${complaint.longitude.toFixed(6)}
Map Location Link      : ${mapLink}
Submission Timestamp   : ${complaint.submission_timestamp}
Responsible Department : ${mapping?.department_name || 'City Administration'}

Issue Title:
${complaint.title}

Detailed Description:
${complaint.description}

Photographic Evidence:
${complaint.photo_url}

Instructions for Municipal Corporation:
- Please quote Reference ID '${complaint.id}' in all correspondence.
- Official complaint tracking portal: https://nagrikvoice.org/complaints/${complaint.id}

==========================================
Generated by NagrikVoice Citizen Platform
One Problem. One Complaint. Verified Civic Accountability.
`;

  const deliveryId = `email_del_${Date.now()}_${attemptNumber}`;
  const providerRef = `prov_${Date.now()}_${Math.random().toString(36).substring(2, 8)}`;
  const idempotencyKey = `idemp_${complaint.id}_attempt_${attemptNumber}`;

  // Initial state: QUEUED / SENDING
  const initialStatus: EmailStatus = 'SENDING';

  db.prepare(`
    INSERT INTO email_deliveries (
      id, complaint_id, attempt_number, recipient_email, is_test_recipient,
      subject, body, status, provider_reference, idempotency_key, created_at, sent_at
    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
  `).run(
    deliveryId,
    complaint.id,
    attemptNumber,
    recipientEmail,
    isTestMode ? 1 : 0,
    subject,
    body,
    initialStatus,
    providerRef,
    idempotencyKey,
    now,
    now
  );

  // If simulate delivery is requested (e.g. In automated tests or local demo)
  if (options.simulateDelivery) {
    if (options.deliveryOutcome === 'FAILED') {
      handleEmailDeliveryFailed(complaint.id, 'Simulated mailbox bounce or SMTP failure', providerRef, db);
      return {
        deliveryId,
        complaintId: complaint.id,
        attemptNumber,
        recipientEmail,
        isTestRecipient: isTestMode,
        subject,
        status: 'FAILED',
        providerReference: providerRef
      };
    } else {
      // Confirmed delivery
      handleEmailDeliveryConfirmed(complaint.id, providerRef, idempotencyKey, db);
      return {
        deliveryId,
        complaintId: complaint.id,
        attemptNumber,
        recipientEmail,
        isTestRecipient: isTestMode,
        subject,
        status: 'DELIVERED',
        providerReference: providerRef
      };
    }
  }

  // Update complaint email status to SENDING
  db.prepare(`
    UPDATE complaints SET email_status = 'SENDING', updated_at = ? WHERE id = ?
  `).run(now, complaint.id);

  return {
    deliveryId,
    complaintId: complaint.id,
    attemptNumber,
    recipientEmail,
    isTestRecipient: isTestMode,
    subject,
    status: initialStatus,
    providerReference: providerRef
  };
}
